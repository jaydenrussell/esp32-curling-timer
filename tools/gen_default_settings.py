#!/usr/bin/env python3
"""Generate external_components/curling_engine/default_settings.h.

The header embeds pitimer's stock example settings (first-boot defaults for
the on-device web editor). Regenerate after changing the source example:

    python tools/gen_default_settings.py

Source defaults to the rpi-buzzer checkout used during the port; pass a path
to override:

    python tools/gen_default_settings.py path/to/pitimer_settings.example.yml
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = Path(
    r"C:\Users\Jayden Russell\Downloads\rpi-buzzer-2.4.4-dev"
    r"\rpi-buzzer-dev\pitimer_settings.example.yml"
)
OUT = REPO / "external_components" / "curling_engine" / "default_settings.h"
DELIM = "PITIMER_DEFAULT"


def main() -> int:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    text = source.read_text(encoding="utf-8")
    if f"){DELIM}\"" in text:
        raise SystemExit(f"example contains raw-literal terminator ){DELIM}\"")
    if not text.endswith("\n"):
        text += "\n"
    header = (
        "#pragma once\n"
        "// GENERATED by tools/gen_default_settings.py — do not edit by hand.\n"
        "// First-boot default settings (pitimer_settings.example.yml content).\n"
        "\n"
        "namespace esphome {\n"
        "namespace curling_engine {\n"
        "\n"
        f'static const char DEFAULT_SETTINGS_YAML[] = R"{DELIM}(\n'
        f"{text}"
        f'){DELIM}";\n'
        "\n"
        "}  // namespace curling_engine\n"
        "}  // namespace esphome\n"
    )
    OUT.write_text(header, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes) from {source}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
